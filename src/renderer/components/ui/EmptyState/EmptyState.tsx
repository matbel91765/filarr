/**
 * EmptyState Component
 *
 * Reusable empty state placeholder for pages with no data.
 * Supports icon, title, description, and optional action button.
 */

import React, { FC, ReactNode } from 'react';

interface EmptyStateProps {
  icon?: ReactNode;
  title: string;
  description?: string;
  action?: {
    label: string;
    onClick: () => void;
  };
  className?: string;
}

export const EmptyState: FC<EmptyStateProps> = ({
  icon,
  title,
  description,
  action,
  className = '',
}) => (
  <div className={`flex flex-col items-center justify-center py-16 px-6 text-center ${className}`}>
    {icon && (
      <div className="mb-4 text-[var(--color-text-tertiary)]">
        {icon}
      </div>
    )}
    <h3 className="text-lg font-semibold text-[var(--color-text-primary)] mb-1">
      {title}
    </h3>
    {description && (
      <p className="text-sm text-[var(--color-text-tertiary)] max-w-sm mb-4">
        {description}
      </p>
    )}
    {action && (
      <button
        onClick={action.onClick}
        className="px-4 py-2 text-sm bg-[var(--color-primary-600)] text-white rounded-lg hover:bg-[var(--color-primary-700)] transition-colors"
      >
        {action.label}
      </button>
    )}
  </div>
);

